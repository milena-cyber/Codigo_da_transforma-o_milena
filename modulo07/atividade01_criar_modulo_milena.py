# Funções que estariam em utilidades.py

def somar(a, b):
    return a + b

def subtrair(a, b):
    return a - b

def multiplicar(a, b):
    return a * b

def dividir(a, b):
    return a / b


# Programa principal

print("Soma:", somar(10, 5))

print("Subtração:", subtrair(10, 5))

print("Multiplicação:", multiplicar(10, 5))

print("Divisão:", dividir(10, 5))